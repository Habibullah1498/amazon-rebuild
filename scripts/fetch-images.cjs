  'bz-3001': 'hardcover book',
  'bz-3002': 'stack of books',
  'bz-3003': 'cookbook',
  'bz-3004': 'paperback book',
  'bz-4001': 'running shoes',
  'bz-4002': 'canvas jacket',
  'bz-4003': 'wrist watch',
  'bz-4004': 'backpack',
  'bz-5001': 'hiking backpack',
