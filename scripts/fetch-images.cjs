// Resolves one Unsplash photo per product by actually searching for it, rather
// than hard-coding photo IDs from memory (which silently yields a landscape shot
// on a headphones card). Output is checked in as src/data/images.js; this script
// only needs re-running when the catalogue changes.
//
// Three things this has to work around:
//   - node's fetch gets served a bot challenge (401); curl's TLS fingerprint passes
//   - the search page is ~600KB and curl often hits --max-time mid-stream, but the
//     <head> preloads the top results in rank order, so a partial body is enough
//     (the bytes received so far arrive on err.stdout)
//   - no shell: a POSIX pipeline isn't portable on Windows
const fs = require('fs');
const path = require('path');
const { execFile } = require('child_process');

