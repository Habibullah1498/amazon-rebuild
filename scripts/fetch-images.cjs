  'bz-1001': 'over ear headphones',
  'bz-1002': 'wireless earbuds',
  'bz-1003': 'laptop computer',
  'bz-1004': 'smartphone',
  'bz-1005': 'mirrorless camera',
  'bz-1006': 'bookshelf speaker',
